def summarize(rows):
    grouped = {}
    for row in rows:
        if row["stage"] != "measured":
            continue
        key = (row["queue_size"], row["mode"], row["batch_size"], row["input_layout"], row["operation"])
        grouped.setdefault(key, []).append(row["ns_per_request"])
    summary = []
    for key, values in sorted(grouped.items()):
        quartiles = statistics.quantiles(values, n=4, method="inclusive")
        mean = statistics.mean(values)
        stdev = statistics.stdev(values)
        summary.append({
            "queue_size": key[0], "mode": key[1], "batch_size": key[2],
            "input_layout": key[3], "operation": key[4], "trials": len(values),
            "median_ns_per_request": statistics.median(values),
            "q1_ns_per_request": quartiles[0], "q3_ns_per_request": quartiles[2],
            "iqr_ns_per_request": quartiles[2] - quartiles[0],
            "min_ns_per_request": min(values), "max_ns_per_request": max(values),
            "mean_ns_per_request": mean, "stdev_ns_per_request": stdev,
            "cv_percent": 100 * stdev / mean,
        })
    return summary


def comparisons(summary):
    lookup = {}
    for row in summary:
        key = (row["queue_size"], row["mode"], row["batch_size"], row["input_layout"], row["operation"])
        lookup[key] = row["median_ns_per_request"]
    output = []
    for row in summary:
        mode = row["mode"]
        if not mode.startswith("rust_"):
            continue
        count, batch, layout, operation = row["queue_size"], row["batch_size"], row["input_layout"], row["operation"]
        baseline_mode = "deque_single" if mode == "rust_single" else "deque_batch"
        natural = lookup[(count, baseline_mode, batch, layout, operation)]
        copy_mode = "deque_copy_single" if mode == "rust_single" else "deque_copy_batch"
        copied = lookup[(count, copy_mode, batch, layout, operation)]
        rust_single = lookup[(count, "rust_single", 1, "individual", operation)]
        deque_single = lookup[(count, "deque_single", 1, "individual", operation)]
        rust = row["median_ns_per_request"]
        output.append({
            "queue_size": count, "mode": mode, "batch_size": batch,
            "input_layout": layout, "operation": operation,
            "rust_ns_per_request": rust,
            "deque_same_api_ns_per_request": natural,
            "deque_same_api_over_rust": natural / rust,
            "deque_single_over_rust": deque_single / rust,
            "deque_copy_same_api_over_rust": copied / rust,
            "rust_single_over_rust": rust_single / rust,
        })
    return output


def write_csv(path, rows):
    with path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def write_markdown(path, summary):
    lines = ["# Local queue measurements", "", "Times are median [Q1, Q3] ns/request; lower is faster.",
             "Quartiles describe retained trials in this process, not confidence intervals.", ""]
    for count in sorted(set(row["queue_size"] for row in summary)):
        lines.extend([f"## Queue size {count}", "",
                      "| Mode | Batch | Input | Enqueue | Dequeue |",
                      "| --- | ---: | --- | ---: | ---: |"])
        groups = {}
        for row in summary:
            if row["queue_size"] == count:
                key = (row["mode"], row["batch_size"], row["input_layout"])
                groups.setdefault(key, {})[row["operation"]] = row
        for key, operations in sorted(groups.items()):
            formatted = []
            for operation in ("enqueue", "dequeue"):
                row = operations[operation]
                formatted.append(f"{row['median_ns_per_request']:.2f} "
                                 f"[{row['q1_ns_per_request']:.2f}, {row['q3_ns_per_request']:.2f}]")
            lines.append(f"| {key[0]} | {key[1]} | {key[2]} | {formatted[0]} | {formatted[1]} |")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sizes", type=int, nargs="+", default=[100, 1000, 10000, 100000])
    parser.add_argument("--batch-sizes", type=int, nargs="+", default=[1, 8, 64, 256, 1024])
    parser.add_argument("--warmups", type=int, default=2)
    parser.add_argument("--trials", type=int, default=9)
    parser.add_argument("--min-phase-ms", type=float, default=5.0)
    parser.add_argument("--seed", type=int, default=263)
    parser.add_argument("--output", required=True, help="A new directory; existing results are never overwritten")
    library_name = "ffi_probe.dll" if sys.platform == "win32" else "libffi_probe.so"
    if sys.platform == "darwin":
        library_name = "libffi_probe.dylib"
    parser.add_argument("--release-library", default=str(ROOT / "target/ffi-probe/release" / library_name))
    args = parser.parse_args()
    if min(args.sizes + args.batch_sizes) < 1 or args.warmups < 1 or args.trials < 3:
        parser.error("Sizes must be positive, with at least one warm-up and three trials")
    if not math.isfinite(args.min_phase_ms) or args.min_phase_ms <= 0:
        parser.error("--min-phase-ms must be finite and positive")
    args.sizes = sorted(set(args.sizes))
    args.batch_sizes = sorted(set(args.batch_sizes))
    return args


def main():
    args = parse_args()
    extension = loaded_extension_path()
    release_library = Path(args.release_library).resolve()
    if not release_library.is_file() or file_hash(extension) != file_hash(release_library):
        raise SystemExit("Loaded extension does not match the release library. Rebuild/install with --release first.")
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=False)
    metadata = environment(args, extension, release_library)
    metadata_path = output / "environment.json"
    metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    cases = make_cases(args.sizes, args.batch_sizes)
    inputs = {}
    prepared = {}
    for count in args.sizes:
        # Data allocation and integer creation are excluded for every backend.
        inputs[count] = [(index + 1000, (index * 17) % 100003, (index * 13) % 997)
                         for index in range(count)]
    for count, mode, batch_size, layout in cases:
        if layout == "prepared" and (count, batch_size) not in prepared:
            prepared[(count, batch_size)] = list(sliced_batches(inputs[count], batch_size))

    cycles = {}
    calibration = []
    for case in cases:
        count, mode, batch_size, layout = case
        times = run_sample(case, inputs[count], prepared.get((count, batch_size)), 1)
        cycle_count = min(10000, max(1, math.ceil(args.min_phase_ms * 1e6 / max(1, min(times)))))
        cycles[case] = cycle_count
        calibration.append({"case": case, "enqueue_ns": times[0], "dequeue_ns": times[1], "cycles": cycle_count})
    metadata["calibration"] = calibration
    metadata["case_count"] = len(cases)
    metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    rng = random.Random(args.seed)
    rows = []
    raw_path = output / "raw.csv"
    for round_index in range(args.warmups + args.trials):
        stage = "warmup" if round_index < args.warmups else "measured"
        trial = round_index + 1 if stage == "warmup" else round_index - args.warmups + 1
        order = cases.copy()
        rng.shuffle(order)
        for order_index, case in enumerate(order):
            count, mode, batch_size, layout = case
            cycle_count = cycles[case]
            times = run_sample(case, inputs[count], prepared.get((count, batch_size)), cycle_count)
            for operation, elapsed in zip(("enqueue", "dequeue"), times):
                rows.append({
                    "stage": stage, "trial": trial, "order_index": order_index,
                    "queue_size": count, "mode": mode, "batch_size": batch_size,
                    "input_layout": layout, "operation": operation, "cycles": cycle_count,
                    "total_requests": count * cycle_count,
                    "queue_api_calls": cycle_count * (math.ceil(count / batch_size) if mode.endswith("batch") else count),
                    "elapsed_ns": elapsed, "ns_per_request": elapsed / (count * cycle_count),
                })
        write_csv(raw_path, rows)
        print(f"{stage} {trial}: {len(cases)} cases checked and saved", flush=True)

    summary = summarize(rows)
    write_csv(output / "summary.csv", summary)
    write_csv(output / "comparisons.csv", comparisons(summary))
    write_markdown(output / "summary.md", summary)
    metadata["finished_utc"] = datetime.now(timezone.utc).isoformat()
    metadata["raw_rows"] = len(rows)
    metadata["status"] = "complete"
    metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"Saved {len(rows)} raw rows and {len(summary)} summaries to {output}")


if __name__ == "__main__":
    main()
