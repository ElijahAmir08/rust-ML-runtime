def enqueue_deque(queue, requests, batches):
    append = queue.append
    for request in requests:
        append(request)


def enqueue_deque_copy(queue, requests, batches):
    append = queue.append
    for id, arrival_ms, duration_ms in requests:
        append((id, arrival_ms, duration_ms))


def enqueue_rust(queue, requests, batches):
    enqueue = queue.enqueue
    for id, arrival_ms, duration_ms in requests:
        enqueue(id, arrival_ms, duration_ms)


def enqueue_deque_batch(queue, requests, batches):
    extend = queue.extend
    for batch in batches:
        extend(batch)


def enqueue_deque_batch_copy(queue, requests, batches):
    extend = queue.extend
    for batch in batches:
        extend([(id, arrival_ms, duration_ms) for id, arrival_ms, duration_ms in batch])


def enqueue_rust_batch(queue, requests, batches):
    enqueue = queue.enqueue_batch
    for batch in batches:
        enqueue(batch)


def dequeue_deque(queue, count, batch_size):
    pop = queue.popleft
    return [pop() for _ in range(count)]


def dequeue_deque_copy(queue, count, batch_size):
    pop = queue.popleft
    removed = []
    for _ in range(count):
        id, arrival_ms, duration_ms = pop()
        removed.append((id, arrival_ms, duration_ms))
    return removed


def dequeue_rust(queue, count, batch_size):
    pop = queue.dequeue
    return [pop() for _ in range(count)]


def dequeue_deque_batch(queue, count, batch_size):
    pop = queue.popleft
    removed = []
    for start in range(0, count, batch_size):
        batch = [pop() for _ in range(min(batch_size, count - start))]
        removed.extend(batch)
    return removed


def dequeue_deque_batch_copy(queue, count, batch_size):
    pop = queue.popleft
    removed = []
    for start in range(0, count, batch_size):
        batch = []
        for _ in range(min(batch_size, count - start)):
            id, arrival_ms, duration_ms = pop()
            batch.append((id, arrival_ms, duration_ms))
        removed.extend(batch)
    return removed


def dequeue_rust_batch(queue, count, batch_size):
    pop = queue.dequeue_batch
    removed = []
    for start in range(0, count, batch_size):
        removed.extend(pop(min(batch_size, count - start)))
    return removed


# Each operation function is called once per timed phase, not once per request.
OPERATIONS = {
    "deque_single": (deque, enqueue_deque, dequeue_deque),
    "deque_copy_single": (deque, enqueue_deque_copy, dequeue_deque_copy),
    "rust_single": (PyRequestQueue, enqueue_rust, dequeue_rust),
    "deque_batch": (deque, enqueue_deque_batch, dequeue_deque_batch),
    "deque_copy_batch": (deque, enqueue_deque_batch_copy, dequeue_deque_batch_copy),
    "rust_batch": (PyRequestQueue, enqueue_rust_batch, dequeue_rust_batch),
}


def sliced_batches(requests, batch_size):
    # Generator bodies run during iteration, so these slices are timed.
    for start in range(0, len(requests), batch_size):
        yield requests[start:start + batch_size]


def make_cases(sizes, batch_sizes):
    cases = []
    for count in sizes:
        for mode in ("deque_single", "deque_copy_single", "rust_single"):
            cases.append((count, mode, 1, "individual"))
        actual_sizes = sorted(set(min(size, count) for size in batch_sizes) | {count})
        for batch_size in actual_sizes:
            for layout in ("prepared", "sliced"):
                for mode in ("deque_batch", "deque_copy_batch", "rust_batch"):
                    cases.append((count, mode, batch_size, layout))
    return cases


def run_sample(case, requests, prepared, cycles):
    count, mode, batch_size, layout = case
    factory, enqueue, dequeue = OPERATIONS[mode]
    enqueue_ns = 0
    dequeue_ns = 0
    gc_was_enabled = gc.isenabled()
    gc.disable()
    try:
        for _ in range(cycles):
            queue = factory()
            batches = sliced_batches(requests, batch_size) if layout == "sliced" else prepared
            start = perf_counter_ns()
            enqueue(queue, requests, batches)
            enqueue_ns += perf_counter_ns() - start
            if len(queue) != count:
                raise AssertionError("Enqueue lost requests")

            start = perf_counter_ns()
            removed = dequeue(queue, count, batch_size)
            dequeue_ns += perf_counter_ns() - start
            if removed != requests or len(queue) != 0:
                raise AssertionError("Dequeue changed FIFO order or request fields")
            # Destroy returned Python tuples/lists outside both timed phases.
            del removed, queue
    finally:
        if gc_was_enabled:
            gc.enable()
    return enqueue_ns, dequeue_ns


def file_hash(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def loaded_extension_path():
    for name, module in list(sys.modules.items()):
        if name == "ffi_probe" or name.startswith("ffi_probe."):
            path = getattr(module, "__file__", "")
            if path and any(path.endswith(suffix) for suffix in importlib.machinery.EXTENSION_SUFFIXES):
                return Path(path).resolve()
    raise RuntimeError("Cannot find the loaded ffi_probe native extension")


def command_output(command):
    try:
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, timeout=15)
        return result.stdout.strip() if result.returncode == 0 else None
    except (OSError, subprocess.TimeoutExpired):
        return None


