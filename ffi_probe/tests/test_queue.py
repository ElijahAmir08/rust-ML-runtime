import random
import struct
import unittest
from collections import deque

from ffi_probe import PyRequestQueue, count_requests, ping

class RequestQueueTests(unittest.TestCase):
    def test_empty_queue(self):
        queue = PyRequestQueue()
        self.assertEqual(len(queue), 0)
        self.assertFalse(queue)
        self.assertIsNone(queue.dequeue())
        self.assertIsNone(queue.dequeue())

    def test_fifo_preserves_fields_and_insertion_order(self):
        queue = PyRequestQueue()
        requests = [(9, 100, 50), (2, 0, 60), (9, 5, 0)]
        for request in requests:
            # Unpack the requests into the seperate arguments 
            queue.enqueue(*request)
        self.assertEqual(len(queue), 3)
        self.assertTrue(queue)

        remaining = len(requests)
        for request in requests:
            self.assertEqual(queue.dequeue(), request)

            remaining -= 1
            self.assertEqual(len(queue), remaining)
        self.assertIsNone(queue.dequeue())

